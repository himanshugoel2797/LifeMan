"""Per-session workspace for the Claude Code build chat.

Each lifeman build session corresponds to one Claude Code session running in
a per-session workspace under `~/.lifeman/build_workspaces/<sid>`. We refresh
`CLAUDE.md` in the workspace before every (re)attach so Claude Code's
project-context loader sees the current registry of installed tools and the
contract for new tools.

The actual conversation runs as a real interactive Claude Code TUI streamed
to the browser through `lifeman.build_terminal`. This module no longer wraps
`--print` / stream-json — it only owns the workspace lifecycle, the
CLAUDE.md generator, and the helpers that read finished tool artifacts back
out for registration.
"""

from __future__ import annotations

import json
import logging
import shutil
from datetime import datetime, timezone
from pathlib import Path
from textwrap import dedent

from lifeman.config import settings
from lifeman.db import get_db

log = logging.getLogger(__name__)


BUILD_SYSTEM_PROMPT = dedent(
    """\
    You are the build-chat assistant for lifeman, a personal companion AI kernel
    described in DESIGN.MD. Read CLAUDE.md in the working directory — it is
    refreshed before every turn with the current list of installed tools,
    their manifests, and the contract for new tools.

    Your job is to design and produce new tools that fit lifeman's contract.
    Discuss the design briefly with the user first, then write the artifacts to
    disk under `./out/<tool_name>/`. When you are done, tell the user the tool
    name so they can click "Register" in the lifeman UI to install it.

    Be concise. Prefer minimal dependencies. Re-use behaviors of existing tools
    where they fit instead of duplicating logic.
    """
)


CONTEXT_HEADER = dedent(
    """\
    # lifeman build-chat context

    This file is auto-regenerated by lifeman before every turn of this build
    session. Treat it as the authoritative ground truth for what tools exist
    and how to add new ones. Anything you write here will be overwritten.

    """
)


class BuildChatError(RuntimeError):
    pass


def workspace_for(session_id: str) -> Path:
    root = settings.get_build_workspace_dir()
    root.mkdir(parents=True, exist_ok=True)
    ws = root / session_id
    ws.mkdir(parents=True, exist_ok=True)
    (ws / "out").mkdir(exist_ok=True)
    return ws


