TOOL_CONTRACT = dedent(
    """\
    ## Tool contract

    A lifeman tool is a directory containing four files. Tools run inside a
    bubblewrap sandbox with read-only access to their own directory and a
    writable `/scratch` tmpfs. Stdin/stdout is JSON.

    ### Files
    - `run.py` — Python 3.12. Reads a JSON object from stdin, writes a JSON
      object to stdout. Exit non-zero on fatal error; otherwise return
      `{"error": "..."}` for recoverable errors so the audit log stays clean.
    - `manifest.json` — capability declaration. Schema below.
    - `schema_input.json` — JSON Schema for the args object.
    - `schema_output.json` — JSON Schema for the result object.

    ### Manifest schema
    ```json
    {
      "description": "human-readable one-liner",
      "category": "general",
      "reads": [],            // data categories the tool may read
      "writes": [],           // data categories the tool may write
      "network": [],          // host allowlist; empty = no network at all
      "compute_limits": {"timeout": 30},
      "triggers": [],         // tools/actions this tool can trigger
      "user_visible": true
    }
    ```
    Unknown fields are ignored at register time but should be omitted.

    ### Sandbox semantics
    - **Network**: the sandbox unshares the network namespace by default,
      so a tool with `network: []` has *no* network access. To request
      network access, list the hosts the tool will contact in
      `manifest.network` (or `["*"]` if you genuinely need open egress —
      flag this for the user). When the list is non-empty, the sandbox
      shares the host's network namespace and `LIFEMAN_NETWORK_HOSTS`
      contains the comma-separated allowlist. Use
      `lifeman_tool.network_allowed(host)` to self-gate requests; the
      manifest declaration is the user-visible contract. The kernel does
      not yet enforce the allowlist at the syscall level (egress proxy
      is future work).
    - No filesystem writes outside `/scratch` (path injected as
      `LIFEMAN_SCRATCH` env var inside the sandbox).
    - Default timeout is 30s; raise `compute_limits.timeout` if you need more.
    - Stdlib only by default. If you need PyPI packages, declare them in the
      design discussion so we can plan how to vendor them.

    ### Conventions
    - Names are `snake_case`. They become the tool's id in the registry.
    - Single responsibility per tool; compose by having tools call each other
      through the core `invoke` API rather than duplicating logic.
    - Every result includes a stable shape — keep field names compatible
      across versions.
    """
)


