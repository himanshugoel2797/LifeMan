_DETAILED_TOOL_LIMIT = 20  # Above this, the long tail collapses to one-liners.


async def render_claude_md() -> str:
    """Build a fresh CLAUDE.md describing the live state of the registry.

    Up to `_DETAILED_TOOL_LIMIT` tools are rendered in full (manifest + both
    schemas + recent invocations). The rest collapse to a single-line
    summary so a registry of 50+ tools doesn't blow up the prompt every
    turn. The most-recently-used tools are picked for the detailed slot
    so Claude sees what's actually in active use.
    """
    db = await get_db()

    # Pick the most-recently-active tools for detailed rendering. LEFT JOIN
    # so tools with no invocations still sort in (under their name) below
    # ones with recent activity.
    rows = await db.execute_fetchall(
        """SELECT t.id, t.name, t.description, t.category,
                  MAX(i.started_at) AS last_used
             FROM tools t
             LEFT JOIN invocations i ON i.tool = t.name
            WHERE t.deprecated_at IS NULL
            GROUP BY t.id
            ORDER BY last_used DESC NULLS LAST, t.name"""
    )
    rows = [dict(r) for r in rows]

    detailed = rows[:_DETAILED_TOOL_LIMIT]
    tail = rows[_DETAILED_TOOL_LIMIT:]

    tool_blocks: list[str] = []
    for r in detailed:
        manifest_rows = await db.execute_fetchall(
            "SELECT manifest_json, schema_input_json, schema_output_json "
            "FROM tool_manifests WHERE tool_id = ? ORDER BY version DESC LIMIT 1",
            (r["id"],),
        )
        manifest: dict = {}
        schema_input: dict = {}
        schema_output: dict = {}
        if manifest_rows:
            m = dict(manifest_rows[0])
            try:
                manifest = json.loads(m["manifest_json"])
            except json.JSONDecodeError:
                manifest = {}
            try:
                schema_input = json.loads(m["schema_input_json"])
            except json.JSONDecodeError:
                schema_input = {}
            try:
                schema_output = json.loads(m["schema_output_json"])
            except json.JSONDecodeError:
                schema_output = {}

        recent = await db.execute_fetchall(
            "SELECT started_at, source, error FROM invocations WHERE tool = ? "
            "ORDER BY started_at DESC LIMIT 3",
            (r["name"],),
        )
        recent_lines = []
        for inv in recent:
            inv = dict(inv)
            status = "error" if inv.get("error") else "ok"
            recent_lines.append(f"  - {inv['started_at'][:19]} via {inv['source']} → {status}")
        recent_block = "\n".join(recent_lines) if recent_lines else "  - (no invocations yet)"

        tool_blocks.append(
            f"### `{r['name']}` — {r['description']}\n"
            f"- id: `{r['id']}`  category: `{r['category']}`\n"
            f"- manifest: `{json.dumps(manifest)}`\n"
            f"- args schema: `{json.dumps(schema_input)}`\n"
            f"- result schema: `{json.dumps(schema_output)}`\n"
            f"- recent invocations:\n{recent_block}\n"
        )

    if tool_blocks:
        installed_section = "## Installed tools\n\n" + "\n".join(tool_blocks)
    else:
        installed_section = (
            "## Installed tools\n\n"
            "_No tools installed yet. You are bootstrapping the registry — pick a tool "
            "the user asks for and build it._\n"
        )

    if tail:
        tail_lines = [
            f"- `{t['name']}` ({t['category']}) — {t['description']}"
            for t in tail
        ]
        installed_section += (
            f"\n### Other installed tools ({len(tail)} more)\n\n"
            "_Listed in compact form — ask for full manifest/schemas if you "
            "need to call or modify them._\n\n"
            + "\n".join(tail_lines) + "\n"
        )

    stamp = datetime.now(timezone.utc).isoformat(timespec="seconds")
    return (
        CONTEXT_HEADER
        + f"_Generated at {stamp}._\n\n"
        + installed_section
        + "\n"
        + TOOL_CONTRACT
        + "\n"
        + WORKSPACE_INSTRUCTIONS
    )


async def refresh_workspace_context(session_id: str) -> Path:
    """Regenerate `CLAUDE.md` in the workspace before a turn."""
    ws = workspace_for(session_id)
    md = await render_claude_md()
    target = ws / "CLAUDE.md"
    target.write_text(md)
    return target


def cleanup_workspace(session_id: str) -> None:
    ws = settings.get_build_workspace_dir() / session_id
    if ws.exists():
        shutil.rmtree(ws, ignore_errors=True)


async def stream_build_turn(
    session_id: str,
    external_id: str | None,
    user_message: str,
) -> AsyncIterator[dict]:
    """Run one Claude Code turn and stream parsed events.

    Yields:
        {"type": "external_id", "value": "..."}        # new claude session id (first turn only)
        {"type": "delta", "text": "..."}               # assistant text delta
        {"type": "tool_use", "id": "...", "name": "...", "input": {...}}
        {"type": "tool_result", "id": "...", "ok": True, "summary": "..."}
        {"type": "permission_denied", "id": "...", "name": "...", "input": {...}, "spec": "..."}
        {"type": "done", "result": "..."}
        {"type": "error", "message": "..."}
    """
    cli = settings.claude_cli
    if not shutil.which(cli) and not Path(cli).exists():
        yield {
            "type": "error",
            "message": (
                f"Claude CLI '{cli}' not found on PATH. Install Claude Code or set "
                f"LIFEMAN_CLAUDE_CLI to its absolute path."
            ),
        }
        return

    workspace = workspace_for(session_id)

    # Refresh CLAUDE.md so Claude Code's project-context loader sees the current
    # registry state before this turn runs.
    try:
        await refresh_workspace_context(session_id)
    except Exception:
        log.exception("failed to refresh CLAUDE.md")

    # Refresh the workspace's `.claude/settings.local.json` so any permission
    # the user granted between turns becomes effective for this one. Defaults
    # are passed on the CLI as well — settings.local.json layers on top.
    try:
        await write_workspace_settings(session_id)
    except Exception:
        log.exception("failed to refresh workspace settings.local.json")

    granted_specs = await session_grant_specs(session_id)

    # On the first turn, let Claude pick its own session id. We learn the id
    # from the `system` init event in the stream and yield it back to the
    # caller (which persists it for subsequent --resume calls). Pre-generating
    # the id and forcing it via --session-id risked silently joining another
    # process's session if a uuid ever collided or the CLI rejected pre-set
    # ids; reading the canonical id from Claude's own output sidesteps that.
    is_first = external_id is None

    args: list[str] = [
        cli,
        "--print",
        "--output-format", "stream-json",
        "--verbose",
        "--permission-mode", "acceptEdits",
        "--append-system-prompt", BUILD_SYSTEM_PROMPT,
    ]
    # Pre-allow the safe surface plus anything the user has explicitly granted
    # for this session. `--allowedTools` is variadic — pass each spec as its
    # own arg so we don't need to worry about quoting/escape rules.
    args.append("--allowedTools")
    args.extend(default_allowed_specs())
    args.extend(granted_specs)
    if not is_first:
        args += ["--resume", external_id]
    args += [user_message]

    log.info(
        "build_chat: spawning claude (resume=%s, cwd=%s)",
        external_id if not is_first else None,
        workspace,
    )

    try:
        proc = await asyncio.create_subprocess_exec(
            *args,
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.PIPE,
            cwd=str(workspace),
        )
    except FileNotFoundError as e:
        yield {"type": "error", "message": f"failed to spawn claude: {e}"}
        return

    # Stream stdout line by line and parse JSON events. The first `system`
    # event carries the canonical session_id; on the first turn we forward it
    # as an `external_id` event so the caller can persist it for resume.
    #
    # We also track in-flight tool_uses by id so that when a tool_result comes
    # back denied, we can re-derive the original tool name + input and emit
    # a `permission_denied` event with a Claude-Code-style spec attached.
    seen_session_id: str | None = None
    in_flight: dict[str, dict] = {}
    assert proc.stdout is not None
    async for raw in proc.stdout:
        line = raw.decode(errors="replace").strip()
        if not line:
            continue
        try:
            evt = json.loads(line)
        except json.JSONDecodeError:
            log.debug("build_chat: non-JSON line: %s", line[:200])
            continue

        # Forward the session id from Claude's init metadata. We trust whatever
        # the CLI tells us — if it differs from the id we passed via --resume,
        # treat the new one as authoritative (the CLI may have created a new
        # session under us if resume failed).
        sid = evt.get("session_id")
        if isinstance(sid, str) and sid and sid != seen_session_id:
            seen_session_id = sid
            if sid != external_id:
                yield {"type": "external_id", "value": sid}

        async for parsed in _parse_event(evt):
            ptype = parsed.get("type")
            if ptype == "tool_use":
                tid = parsed.get("id") or ""
                if tid:
                    in_flight[tid] = {
                        "name": parsed.get("name", ""),
                        "input": parsed.get("input") or {},
                    }
                yield parsed
            elif ptype == "tool_result":
                yield parsed
                if not parsed.get("ok") and looks_like_permission_denial(
                    parsed.get("summary", "")
                ):
                    tid = parsed.get("id") or ""
                    use = in_flight.get(tid) or {}
                    name = use.get("name") or ""
                    tool_input = use.get("input") or {}
                    spec = derive_permission_spec(name, tool_input)
                    yield {
                        "type": "permission_denied",
                        "id": tid,
                        "name": name,
                        "input": tool_input,
                        "spec": spec,
                        "summary": parsed.get("summary", ""),
                    }
                # Result for this id has been observed; drop the use record.
                in_flight.pop(parsed.get("id") or "", None)
            else:
                yield parsed

    rc = await proc.wait()
    if rc != 0:
        stderr = b""
        if proc.stderr is not None:
            try:
                stderr = await proc.stderr.read()
            except Exception:
                pass
        yield {
            "type": "error",
            "message": f"claude exited {rc}: {stderr.decode(errors='replace')[:400]}",
        }


async def _parse_event(evt: dict) -> AsyncIterator[dict]:
    """Translate one Claude Code stream-json event into our event vocabulary."""
    etype = evt.get("type")

    if etype == "assistant":
        msg = evt.get("message") or {}
        for block in msg.get("content") or []:
            btype = block.get("type")
            if btype == "text":
                text = block.get("text") or ""
                if text:
                    yield {"type": "delta", "text": text}
            elif btype == "tool_use":
                yield {
                    "type": "tool_use",
                    "id": block.get("id", ""),
                    "name": block.get("name", ""),
                    "input": block.get("input") or {},
                }

    elif etype == "user":
        # tool_result blocks come back as user-role messages
        msg = evt.get("message") or {}
        for block in msg.get("content") or []:
            if block.get("type") == "tool_result":
                content = block.get("content")
                if isinstance(content, list):
                    summary = "".join(
                        (c.get("text") or "") for c in content if isinstance(c, dict)
                    )
                else:
                    summary = str(content) if content is not None else ""
                yield {
                    "type": "tool_result",
                    "id": block.get("tool_use_id", ""),
                    "ok": not block.get("is_error", False),
                    "summary": summary[:400],
                }

    elif etype == "result":
        # Final terminator; payload contains the full assistant result text
        yield {"type": "done", "result": evt.get("result", "")}

    elif etype == "system":
        # init / metadata; ignore
        return

    elif etype == "error":
        yield {"type": "error", "message": evt.get("message", "claude error")}


def list_workspace_tools(session_id: str) -> list[dict]:
    """Inspect the workspace's `out/` dir for finished tool artifacts."""
    ws = settings.get_build_workspace_dir() / session_id / "out"
    if not ws.exists():
        return []
    tools = []
    for tool_dir in sorted(ws.iterdir()):
        if not tool_dir.is_dir():
            continue
        run_py = tool_dir / "run.py"
        manifest_path = tool_dir / "manifest.json"
        if not run_py.exists():
            continue
        manifest = {}
        if manifest_path.exists():
            try:
                manifest = json.loads(manifest_path.read_text())
            except json.JSONDecodeError:
                manifest = {"_parse_error": True}
        tools.append({
            "name": tool_dir.name,
            "path": str(tool_dir),
            "manifest": manifest,
            "code_size": run_py.stat().st_size,
        })
    return tools


def read_workspace_tool(session_id: str, name: str) -> dict | None:
    """Read a finished tool's files for registration. Returns None if missing."""
    ws = settings.get_build_workspace_dir() / session_id / "out" / name
    run_py = ws / "run.py"
    if not run_py.exists():
        return None

    code = run_py.read_text()
    manifest_path = ws / "manifest.json"
    schema_in_path = ws / "schema_input.json"
    schema_out_path = ws / "schema_output.json"

    manifest: dict = {}
    if manifest_path.exists():
        try:
            manifest = json.loads(manifest_path.read_text())
        except json.JSONDecodeError:
            manifest = {}

    description = manifest.pop("description", "") if isinstance(manifest, dict) else ""
    category = manifest.pop("category", "general") if isinstance(manifest, dict) else "general"

    def _safe_load(p: Path) -> dict:
        if not p.exists():
            return {}
        try:
            return json.loads(p.read_text())
        except json.JSONDecodeError:
            return {}

    return {
        "name": name,
        "description": description,
        "category": category,
        "manifest": manifest,
        "schema_input": _safe_load(schema_in_path),
        "schema_output": _safe_load(schema_out_path),
        "code": code,
    }
