_DETAILED_TOOL_LIMIT = 20  # Above this, the long tail collapses to one-liners.


async def render_claude_md() -> str:
    """Build a fresh CLAUDE.md describing the live state of the registry.

    Up to `_DETAILED_TOOL_LIMIT` tools are rendered in full (manifest + both
    schemas + recent invocations). The rest collapse to a single-line
    summary so a registry of 50+ tools doesn't blow up the prompt every
    turn. The most-recently-used tools are picked for the detailed slot
    so Claude sees what's actually in active use.
    """
    db = await get_db()

    # Pick the most-recently-active tools for detailed rendering. LEFT JOIN
    # so tools with no invocations still sort in (under their name) below
    # ones with recent activity.
    rows = await db.execute_fetchall(
        """SELECT t.id, t.name, t.description, t.category,
                  MAX(i.started_at) AS last_used
             FROM tools t
             LEFT JOIN invocations i ON i.tool = t.name
            WHERE t.deprecated_at IS NULL
            GROUP BY t.id
            ORDER BY last_used DESC NULLS LAST, t.name"""
    )
    rows = [dict(r) for r in rows]

    detailed = rows[:_DETAILED_TOOL_LIMIT]
    tail = rows[_DETAILED_TOOL_LIMIT:]

    tool_blocks: list[str] = []
    for r in detailed:
        manifest_rows = await db.execute_fetchall(
            "SELECT manifest_json, schema_input_json, schema_output_json "
            "FROM tool_manifests WHERE tool_id = ? ORDER BY version DESC LIMIT 1",
            (r["id"],),
        )
        manifest: dict = {}
        schema_input: dict = {}
        schema_output: dict = {}
        if manifest_rows:
            m = dict(manifest_rows[0])
            try:
                manifest = json.loads(m["manifest_json"])
            except json.JSONDecodeError:
                manifest = {}
            try:
                schema_input = json.loads(m["schema_input_json"])
            except json.JSONDecodeError:
                schema_input = {}
            try:
                schema_output = json.loads(m["schema_output_json"])
            except json.JSONDecodeError:
                schema_output = {}

        recent = await db.execute_fetchall(
            "SELECT started_at, source, error FROM invocations WHERE tool = ? "
            "ORDER BY started_at DESC LIMIT 3",
            (r["name"],),
        )
        recent_lines = []
        for inv in recent:
            inv = dict(inv)
            status = "error" if inv.get("error") else "ok"
            recent_lines.append(f"  - {inv['started_at'][:19]} via {inv['source']} → {status}")
        recent_block = "\n".join(recent_lines) if recent_lines else "  - (no invocations yet)"

        tool_blocks.append(
            f"### `{r['name']}` — {r['description']}\n"
            f"- id: `{r['id']}`  category: `{r['category']}`\n"
            f"- manifest: `{json.dumps(manifest)}`\n"
            f"- args schema: `{json.dumps(schema_input)}`\n"
            f"- result schema: `{json.dumps(schema_output)}`\n"
            f"- recent invocations:\n{recent_block}\n"
        )

    if tool_blocks:
        installed_section = "## Installed tools\n\n" + "\n".join(tool_blocks)
    else:
        installed_section = (
            "## Installed tools\n\n"
            "_No tools installed yet. You are bootstrapping the registry — pick a tool "
            "the user asks for and build it._\n"
        )

    if tail:
        tail_lines = [
            f"- `{t['name']}` ({t['category']}) — {t['description']}"
            for t in tail
        ]
        installed_section += (
            f"\n### Other installed tools ({len(tail)} more)\n\n"
            "_Listed in compact form — ask for full manifest/schemas if you "
            "need to call or modify them._\n\n"
            + "\n".join(tail_lines) + "\n"
        )

    stamp = datetime.now(timezone.utc).isoformat(timespec="seconds")
    return (
        CONTEXT_HEADER
        + f"_Generated at {stamp}._\n\n"
        + installed_section
        + "\n"
        + TOOL_CONTRACT
        + "\n"
        + WORKSPACE_INSTRUCTIONS
    )


async def refresh_workspace_context(session_id: str) -> Path:
    """Regenerate `CLAUDE.md` in the workspace before a turn."""
    ws = workspace_for(session_id)
    md = await render_claude_md()
    target = ws / "CLAUDE.md"
    target.write_text(md)
    return target


def cleanup_workspace(session_id: str) -> None:
    ws = settings.get_build_workspace_dir() / session_id
    if ws.exists():
        shutil.rmtree(ws, ignore_errors=True)


def list_workspace_tools(session_id: str) -> list[dict]:
    """Inspect the workspace's `out/` dir for finished tool artifacts."""
    ws = settings.get_build_workspace_dir() / session_id / "out"
    if not ws.exists():
        return []
    tools = []
    for tool_dir in sorted(ws.iterdir()):
        if not tool_dir.is_dir():
            continue
        run_py = tool_dir / "run.py"
        manifest_path = tool_dir / "manifest.json"
        if not run_py.exists():
            continue
        manifest = {}
        if manifest_path.exists():
            try:
                manifest = json.loads(manifest_path.read_text())
            except json.JSONDecodeError:
                manifest = {"_parse_error": True}
        tools.append({
            "name": tool_dir.name,
            "path": str(tool_dir),
            "manifest": manifest,
            "code_size": run_py.stat().st_size,
        })
    return tools


def read_workspace_tool(session_id: str, name: str) -> dict | None:
    """Read a finished tool's files for registration. Returns None if missing."""
    ws = settings.get_build_workspace_dir() / session_id / "out" / name
    run_py = ws / "run.py"
    if not run_py.exists():
        return None

    code = run_py.read_text()
    manifest_path = ws / "manifest.json"
    schema_in_path = ws / "schema_input.json"
    schema_out_path = ws / "schema_output.json"

    manifest: dict = {}
    if manifest_path.exists():
        try:
            manifest = json.loads(manifest_path.read_text())
        except json.JSONDecodeError:
            manifest = {}

    description = manifest.pop("description", "") if isinstance(manifest, dict) else ""
    category = manifest.pop("category", "general") if isinstance(manifest, dict) else "general"

    def _safe_load(p: Path) -> dict:
        if not p.exists():
            return {}
        try:
            return json.loads(p.read_text())
        except json.JSONDecodeError:
            return {}

    return {
        "name": name,
        "description": description,
        "category": category,
        "manifest": manifest,
        "schema_input": _safe_load(schema_in_path),
        "schema_output": _safe_load(schema_out_path),
        "code": code,
    }
